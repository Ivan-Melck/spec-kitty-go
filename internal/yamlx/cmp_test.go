package yamlx

import (
	"os"
	"testing"

	"github.com/spec-kitty/go-kitty3/internal/jsonx"
)

func TestAgainstRuamel(t *testing.T) {
	dir := "testdata" // generated by Python json/ruamel (see scripts in git history)
	b, _ := os.ReadFile(dir + "/doc.json")
	doc, err := jsonx.DecodeObject(b)
	if err != nil {
		t.Fatal(err)
	}
	want, _ := os.ReadFile(dir + "/ruamel.yaml")
	got := Emit(doc)
	if got != string(want) {
		os.WriteFile(dir+"/go.yaml", []byte(got), 0o644)
		t.Fatalf("mismatch; see %s/go.yaml", dir)
	}
}
