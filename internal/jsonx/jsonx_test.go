package jsonx

import (
	"os"
	"testing"
)

func TestAgainstPython(t *testing.T) {
	dir := "testdata" // generated by Python json/ruamel (see scripts in git history)
	in, _ := os.ReadFile(dir + "/in.json")
	v, err := Decode(in)
	if err != nil {
		t.Fatal(err)
	}
	cases := map[string]Options{
		"pretty.json":      Pretty,
		"sorted_utf8.json": {Indent: 2, SortKeys: true},
		"line.json":        Line,
		"compact.json":     {Indent: -1, SortKeys: true, EnsureASCII: true, Compact: true},
	}
	for f, o := range cases {
		want, _ := os.ReadFile(dir + "/" + f)
		if got := Dumps(v, o); got != string(want) {
			t.Errorf("%s:\nwant %s\ngot  %s", f, want, got)
		}
	}
}

func TestOrder(t *testing.T) {
	o := NewObject("b", 1, "a", 2)
	if got := Dumps(o, Line); got != `{"a": 2, "b": 1}` {
		t.Fatal(got)
	}
	if got := Dumps(o, Options{Indent: -1}); got != `{"b": 1, "a": 2}` {
		t.Fatal(got)
	}
}
