// MinSkillCount is the minimum number of command skills a bundle carries.
const MinSkillCount = 14

var reSemver = regexp.MustCompile(`^\d+\.\d+\.\d+`)

const bashWrapper = `#!/usr/bin/env bash
# Spec Kitty runtime bootstrap — PATH-check with uvx fallback.
# Generated by spec-kitty plugin build. Do not edit manually.
set -euo pipefail

VERSION="{version}"

if command -v spec-kitty >/dev/null 2>&1 && spec-kitty --version >/dev/null 2>&1; then
    exec spec-kitty "$@"
fi

if command -v uvx >/dev/null 2>&1; then
    exec uvx "spec-kitty-cli==${VERSION}" "$@"
fi

echo "Error: spec-kitty is not installed and uvx is not available." >&2
echo "Install spec-kitty: pip install spec-kitty-cli" >&2
exit 1
`

const cmdWrapper = `@echo off
REM Spec Kitty runtime bootstrap for Windows.
REM Generated by spec-kitty plugin build. Do not edit manually.
SET VERSION={version}

where spec-kitty >nul 2>&1
IF ERRORLEVEL 1 GOTO try_uvx
CALL spec-kitty --version >nul 2>&1
IF ERRORLEVEL 1 GOTO try_uvx
spec-kitty %*
EXIT /B %ERRORLEVEL%

:try_uvx
where uvx >nul 2>&1
IF ERRORLEVEL 1 GOTO no_runtime
uvx spec-kitty-cli==%VERSION% %*
EXIT /B %ERRORLEVEL%

:no_runtime
echo Error: spec-kitty is not installed and uvx is not available.
echo Install spec-kitty: pip install spec-kitty-cli
EXIT /B 1
`

// WrapperBash is wrapper_bash_content.
func WrapperBash(version string) string { return strings.Replace(bashWrapper, "{version}", version, 1) }

// WrapperCmd is wrapper_cmd_content.
func WrapperCmd(version string) string { return strings.Replace(cmdWrapper, "{version}", version, 1) }

// commandMembers renders every canonical command skill to
// <prefix>/<spec-kitty.cmd>/SKILL.md (paths relative to root). The command
// source root is "/" upstream, whose missing config is logged.
func commandMembers(stderr io.Writer, root, prefix string) ([]StagedFile, error) {
	rich.LogWarning(stderr, "Config file not found: /.kittify/config.yaml")
	var out []StagedFile
	for _, cmd := range agents.CommandSkillCommands {
		content, err := agents.RenderCommandSkill("", cmd)
		if err != nil {
			return nil, &BuildError{err.Error()}
		}
		out = append(out, staged(relTo(root, filepath.Join(prefix, "spec-kitty."+cmd, "SKILL.md")), content))
	}
	if len(out) < MinSkillCount {
		return nil, errorf("Expected at least %d skills, found %d. Check CANONICAL_COMMANDS in command_installer.", MinSkillCount, len(out))
	}
	return out, nil
}

// finish is finish_build after a successful preparation.
func finish(stderr io.Writer, root string, files []StagedFile, bundleDirs []string, version string) error {
	if version != "" && !reSemver.MatchString(version) {
		io.WriteString(stderr, "Warning: version "+pyjson.ReprString(version)+" is not a clean semver string; the validator may reject it.\n")
	}
	return stage(root, files, bundleDirs)
}

// prepFail collapses a preparation failure (OSError/ValueError/BuildError)
// into the BuildError finish_build raises.
func prepFail(err error) error {
	var be *BuildError
	if errors.As(err, &be) {
		return be
	}
	var pe *pyError
	if errors.As(err, &pe) && pe.Type != "ValueError" {
		return err
	}
	if pe != nil {
		return &BuildError{pe.Msg}
	}
	return &BuildError{err.Error()}
}

// ProfileRepositoryPath stands in for the installed
// charter/offering/agent_profiles/repository.py (a site-packages path a Go
// binary does not have) in the warnings that module emits.
const ProfileRepositoryPath = "<spec-kitty>/charter/offering/agent_profiles/repository.py"

// BuildClaude is ClaudeBundleProjector(outputDir).build minus validation;
// it returns the bundle directory as displayed upstream.
func BuildClaude(stderr io.Writer, outputDir string) (string, error) {
	root, output, err := stagingRoot(outputDir)
	if err != nil {
		return "", err
	}
	directory := filepath.Join(output, "claude-code")
	version := app.Version
	files, err := func() ([]StagedFile, error) {
		files, err := commandMembers(stderr, root, filepath.Join(directory, "skills"))
		if err != nil {
			return nil, err
		}
		// _build_active_charter_service(staging root, org_roots=[]): the
		// built-in profiles plus the staging root's project-layer profiles.
		set := charter.LoadAgentProfileSet(root)
		for _, c := range set.Collisions {
			// warnings.warn routed through logging (captureWarnings); the
			// reporting frame is repository.py:558 in the installed package.
			rich.LogWarning(stderr, ProfileRepositoryPath+":558: ArtifactLayerCollisionWarning: "+c.WarningMessage()+
				"\n  self._record_profile_collision_if_present(\n")
		}
		if len(set.Skipped) > 0 {
			return nil, &BuildError{"Invalid built-in profile sources: " + charter.SkippedReprList(set.Skipped)}
		}
		var profiles []agents.Profile
		for _, o := range set.Profiles {
			if p := agents.ProfileFromObject(o); !p.Sentinel {
				profiles = append(profiles, p)
			}
		}
		if len(profiles) == 0 {
			return nil, errorf("No built-in agent profiles found under %s. Bundle must include profiles per FR-020.", agents.ProfilesAssetDir)
		}
		var agentPaths []string
		for _, p := range profiles {
			rel := relTo(root, filepath.Join(directory, "agents", p.ID+".md"))
			files = append(files, StagedFile{Path: rel, Content: []byte(agents.RenderMarkdownProfile(p)), Mode: 0o644, Managed: true})
			agentPaths = append(agentPaths, "./agents/"+p.ID+".md")
		}
		hooksRel := relTo(root, filepath.Join(directory, "hooks", "hooks.json"))
		hookState, err := observeConfined(root, hooksRel)
		if err != nil {
			return nil, err
		}
		if hookState.kind != "file" && hookState.kind != "absent" {
			return nil, &BuildError{"Unknown hook destination is not a regular file"}
		}
		hooks := jsonLegacy(jsonx.NewObject("hooks", &jsonx.Object{}))
		hookMode := os.FileMode(0o644)
		if hookState.kind == "file" {
			if hooks, err = os.ReadFile(filepath.Join(root, hooksRel)); err != nil {
				return nil, err
			}
			hookMode = hookState.mode
		}
		text, err := pyjson.DecodeUTF8(hooks)
		if err != nil {
			return nil, err
		}
		hookData, err := pyjson.Loads(text)
		if err != nil {
			return nil, err
		}
		hd, ok := hookData.(*jsonx.Object)
		if !ok {
			return nil, &BuildError{"Required Claude hooks must be a JSON object"}
		}
		hasHooks := hd.Len() > 0 && !(hd.Len() == 1 && isEmptyHooks(hd))
		var skills []string
		for _, f := range files {
			if path.Base(f.Path) == "SKILL.md" {
				skills = append(skills, "./"+relTo(directory, filepath.Join(root, path.Dir(f.Path))))
			}
		}
		sort.Strings(skills)
		sort.Strings(agentPaths)
		if len(skills) == 0 {
			return nil, &BuildError{"Claude plugin manifest has no skills to declare."}
		}
		manifest := jsonx.NewObject(
			"name", "spec-kitty",
			"displayName", "Spec Kitty",
			"version", version,
			"description", "Spec-Driven Development toolkit — spec, plan, implement, review, merge.",
			"author", jsonx.NewObject("name", "Spec Kitty", "url", "https://github.com/spec-kitty/spec-kitty"),
			"skills", toAny(skills),
			"agents", toAny(agentPaths),
		)
		if hasHooks {
			manifest.Set("hooks", "hooks/hooks.json")
		}
		marketplace := jsonx.NewObject(
			"name", "spec-kitty-plugins",
			"description", "Spec Kitty skills, agent profiles, and runtime wrappers for Claude Code.",
			"version", version,
			"owner", jsonx.NewObject("name", "Spec Kitty"),
			"plugins", []any{jsonx.NewObject(
				"name", "spec-kitty",
				"source", jsonx.NewObject("source", "git-subdir", "url", "https://github.com/spec-kitty/spec-kitty.git", "path", "dist/spec-kitty-plugins/claude-code"),
				"category", "Developer Tools",
			)},
		)
		files = append(files,
			StagedFile{Path: hooksRel, Content: hooks, Mode: hookMode, Managed: hookState.kind == "absent"},
			StagedFile{Path: relTo(root, filepath.Join(directory, "bin", "spec-kitty-wrapper")), Content: []byte(WrapperBash(version)), Mode: 0o700, Managed: true},
			StagedFile{Path: relTo(root, filepath.Join(directory, "bin", "spec-kitty-wrapper.cmd")), Content: []byte(WrapperCmd(version)), Mode: 0o644, Managed: true},
			StagedFile{Path: relTo(root, filepath.Join(directory, ".claude-plugin", "plugin.json")), Content: jsonLegacy(manifest), Mode: 0o644, Manifest: true, Managed: true},
			StagedFile{Path: relTo(root, filepath.Join(output, "marketplace.json")), Content: jsonLegacy(marketplace), Mode: 0o644, Manifest: true, Managed: true},
		)
		return files, nil
	}()
	if err != nil {
		return "", prepFail(err)
	}
	if err := finish(stderr, root, files, []string{relTo(root, output)}, version); err != nil {
		return "", err
	}
	return path.Join(pyPath(outputDir), "claude-code"), nil
}

func isEmptyHooks(o *jsonx.Object) bool {
	v, ok := o.Get("hooks")
	if !ok {
		return false
	}
	h, ok := v.(*jsonx.Object)
	return ok && h.Len() == 0
}

func toAny(xs []string) []any {
	out := make([]any, len(xs))
	for i, x := range xs {
		out[i] = x
	}
	return out
}

// BuildCodex is CodexBundleProjector(outputDir).build's staging step; it
// returns the bundle directory as displayed upstream.
func BuildCodex(stderr io.Writer, outputDir string) (string, error) {
	bundleDir := path.Join(pyPath(outputDir), "codex")
	root, directory, err := stagingRoot(bundleDir)
	if err != nil {
		return "", err
	}
	version := app.Version
	files, err := commandMembers(stderr, root, filepath.Join(directory, "skills"))
	if err != nil {
		return "", prepFail(err)
	}
	manifest := jsonx.NewObject(
		"name", "spec-kitty",
		"version", version,
		"description", "Spec-Driven Development toolkit.",
		"author", jsonx.NewObject("name", "Spec Kitty"),
		"interface", jsonx.NewObject("displayName", "Spec Kitty", "shortDescription", "Spec-Driven Development for teams."),
		"skills", "skills/",
	)
	marketplace := jsonx.NewObject(
		"name", "spec-kitty-plugins",
		"interface", jsonx.NewObject("displayName", "Spec Kitty Plugins"),
		"plugins", []any{jsonx.NewObject(
			"name", "spec-kitty",
			"source", jsonx.NewObject("source", "local", "path", "."),
			"policy", jsonx.NewObject("installation", "AVAILABLE", "authentication", "ON_INSTALL"),
			"category", "Productivity",
		)},
	)
	files = append(files,
		StagedFile{Path: relTo(root, filepath.Join(directory, ".codex-plugin", "plugin.json")), Content: jsonLegacy(manifest), Mode: 0o644, Manifest: true, Managed: true},
		StagedFile{Path: relTo(root, filepath.Join(directory, "marketplace.json")), Content: jsonLegacy(marketplace), Mode: 0o644, Manifest: true, Managed: true},
	)
	if err := finish(stderr, root, files, []string{relTo(root, directory)}, version); err != nil {
		return "", err
	}
	return bundleDir, nil
}

// pyPath renders str(pathlib.Path(s)).
func pyPath(s string) string {
	abs := strings.HasPrefix(s, "/")
	var parts []string
	for _, p := range strings.Split(s, "/") {
		if p != "" && p != "." {
			parts = append(parts, p)
		}
	}
	out := strings.Join(parts, "/")
	switch {
	case abs:
		return "/" + out
	case out == "":
		return "."
	}
	return out
}
