// MetadataHeader opens every metadata.yaml.
const MetadataHeader = "# Spec Kitty Project Metadata\n# Auto-generated by spec-kitty init/upgrade\n# DO NOT EDIT MANUALLY\n\n"

// CurrentSchemaVersion and the capability set stamped by init/upgrade.
const (
	CurrentSchemaVersion = 3
	MinSupportedSchema   = 3
	MaxSupportedSchema   = 3
)

// SchemaCapabilities is CURRENT_SCHEMA_CAPABILITIES (ordered).
var SchemaCapabilities = []string{"canonical_context", "event_log_authority", "ownership_manifest", "thin_shims"}

// MetadataPath is <root>/.kittify/metadata.yaml.
func MetadataPath(root string) string { return Path(root, MetadataFile) }

// MigrationRecord is one migrations.applied entry.
type MigrationRecord struct {
	ID        string
	AppliedAt string // isoformat
	Result    string // success, skipped, failed
	Notes     *string
}

// Metadata is ProjectMetadata. Timestamps are kept as isoformat strings.
type Metadata struct {
	Version         string
	InitializedAt   string
	LastUpgradedAt  string // "" = null
	PythonVersion   string
	Platform        string
	PlatformVersion string
	Applied         []MigrationRecord
	SchemaVersion   *int
}

func parseMetadataDoc(b []byte) (*jsonx.Object, error) {
	b = bytes.TrimPrefix(b, []byte("\xef\xbb\xbf"))
	v, err := yamlx.Parse(b)
	if err != nil {
		return nil, err
	}
	o, _ := v.(*jsonx.Object)
	return o, nil
}

// LoadMetadataDoc returns the raw parsed metadata.yaml (nil when absent or
// not a mapping).
func LoadMetadataDoc(root string) (*jsonx.Object, error) {
	b, err := os.ReadFile(MetadataPath(root))
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil, nil
		}
		return nil, err
	}
	return parseMetadataDoc(b)
}

// LoadMetadata is ProjectMetadata.load (nil when absent/unreadable/empty).
func LoadMetadata(root string) *Metadata {
	doc, err := LoadMetadataDoc(root)
	if err != nil || doc == nil || doc.Len() == 0 {
		return nil
	}
	sk := doc.GetObject("spec_kitty")
	if sk == nil {
		sk = &jsonx.Object{}
	}
	env := doc.GetObject("environment")
	if env == nil {
		env = &jsonx.Object{}
	}
	m := &Metadata{Version: "unknown"}
	if v, ok := sk.Get("version"); ok && v != nil {
		m.Version = textValue(v)
	}
	if s := sk.GetString("initialized_at"); s != "" {
		if _, err := clock.ParseISO(s); err == nil {
			m.InitializedAt = s
		}
	}
	if m.InitializedAt == "" {
		m.InitializedAt = clock.NowUTCISO()
	}
	if s := sk.GetString("last_upgraded_at"); s != "" {
		if _, err := clock.ParseISO(s); err == nil {
			m.LastUpgradedAt = s
		}
	}
	if v, ok := sk.Get("schema_version"); ok && v != nil {
		switch t := v.(type) {
		case int:
			m.SchemaVersion = &t
		case string:
			var n int
			if _, err := fmt.Sscanf(strings.TrimSpace(t), "%d", &n); err == nil {
				m.SchemaVersion = &n
			}
		}
	}
	m.PythonVersion = env.GetString("python_version")
	m.Platform = env.GetString("platform")
	m.PlatformVersion = env.GetString("platform_version")
	if mig := doc.GetObject("migrations"); mig != nil {
		for _, x := range mig.GetList("applied") {
			r, ok := x.(*jsonx.Object)
			if !ok || !r.Has("id") || !r.Has("applied_at") || !r.Has("result") {
				continue
			}
			rec := MigrationRecord{ID: textValue(mustGet(r, "id")), AppliedAt: r.GetString("applied_at"), Result: textValue(mustGet(r, "result"))}
			if _, err := clock.ParseISO(rec.AppliedAt); err != nil {
				continue
			}
			if n, ok := r.Get("notes"); ok && n != nil {
				s := textValue(n)
				rec.Notes = &s
			}
			m.Applied = append(m.Applied, rec)
		}
	}
	return m
}

func mustGet(o *jsonx.Object, k string) any { v, _ := o.Get(k); return v }

// HasMigration reports a successful record for id.
func (m *Metadata) HasMigration(id string) bool {
	for _, r := range m.Applied {
		if r.ID == id && r.Result == "success" {
			return true
		}
	}
	return false
}

// RecordMigration appends (id, result) unless an identical pair exists.
func (m *Metadata) RecordMigration(id, result string, notes *string) bool {
	for _, r := range m.Applied {
		if r.ID == id && r.Result == result {
			return false
		}
	}
	m.Applied = append(m.Applied, MigrationRecord{ID: id, AppliedAt: clock.NowUTCISO(), Result: result, Notes: notes})
	return true
}

func (m *Metadata) owned() *jsonx.Object {
	sk := jsonx.NewObject("version", m.Version, "initialized_at", m.InitializedAt, "last_upgraded_at", nullable(m.LastUpgradedAt))
	if m.SchemaVersion != nil {
		sk.Set("schema_version", *m.SchemaVersion)
	}
	applied := make([]any, 0, len(m.Applied))
	for _, r := range m.Applied {
		var notes any
		if r.Notes != nil {
			notes = *r.Notes
		}
		applied = append(applied, jsonx.NewObject("id", r.ID, "applied_at", r.AppliedAt, "result", r.Result, "notes", notes))
	}
	return jsonx.NewObject(
		"spec_kitty", sk,
		"environment", jsonx.NewObject("python_version", m.PythonVersion, "platform", m.Platform, "platform_version", m.PlatformVersion),
		"migrations", jsonx.NewObject("applied", applied),
	)
}

func maskVolatile(text string) string {
	lines := strings.Split(strings.TrimRight(text, "\n"), "\n")
	for i, l := range lines {
		st := strings.TrimLeft(l, " \t")
		if strings.HasPrefix(st, "last_upgraded_at:") {
			lines[i] = l[:len(l)-len(st)] + "last_upgraded_at: <masked>"
		}
	}
	return strings.Join(lines, "\n")
}

// Save is ProjectMetadata.save: merge model-owned keys onto the on-disk
// mapping, PyYAML-dump, skip when only last_upgraded_at changed, write
// atomically (0600). Returns whether the file was written.
func (m *Metadata) Save(root string) (bool, error) {
	path := MetadataPath(root)
	var existing *jsonx.Object
	existingText, err := os.ReadFile(path)
	hasExisting := err == nil
	if hasExisting {
		v, perr := yamlx.Parse(bytes.TrimPrefix(existingText, []byte("\xef\xbb\xbf")))
		if perr != nil {
			return false, fmt.Errorf("metadata.yaml is not valid YAML, refusing to rewrite it: %s", path)
		}
		existing, _ = v.(*jsonx.Object)
	}
	if existing == nil {
		existing = &jsonx.Object{}
	}
	merged := existing.Clone()
	for _, kv := range m.owned().Pairs() {
		block := &jsonx.Object{}
		if d, ok := merged.Get(kv.Key); ok {
			if o, isObj := d.(*jsonx.Object); isObj {
				block = o.Clone()
			}
		}
		for _, x := range kv.Value.(*jsonx.Object).Pairs() {
			block.Set(x.Key, x.Value)
		}
		merged.Set(kv.Key, block)
	}
	content := MetadataHeader + yamlx.EmitWith(merged, yamlx.Options{NullAsNull: true})
	if hasExisting && maskVolatile(string(bytes.TrimPrefix(existingText, []byte("\xef\xbb\xbf")))) == maskVolatile(content) {
		return false, nil
	}
	return true, writeAtomic(path, []byte(content), 0o600)
}

func capabilitiesObject() *jsonx.Object {
	o := &jsonx.Object{}
	for _, c := range SchemaCapabilities {
		o.Set(c, true)
	}
	return o
}

// StampSchema is init._stamp_schema_metadata: insert spec_kitty.schema_version
// (first) and schema_capabilities when missing, ruamel round-trip style.
func StampSchema(root string) (bool, error) {
	path := MetadataPath(root)
	b, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		doc := jsonx.NewObject("spec_kitty", jsonx.NewObject("schema_version", CurrentSchemaVersion, "schema_capabilities", capabilitiesObject()))
		if err := os.MkdirAll(Path(root), 0o755); err != nil {
			return false, err
		}
		return true, writeInPlace(path, []byte(yamlx.Emit(doc)), 0o644)
	}
	if err != nil {
		return false, err
	}
	header, body := splitLeadingComments(string(b))
	v, err := yamlx.Parse([]byte(body))
	if err != nil {
		return false, err
	}
	var doc *jsonx.Object
	if v == nil {
		doc = &jsonx.Object{}
	} else if o, ok := v.(*jsonx.Object); ok {
		doc = o
	} else {
		return false, nil
	}
	sk, _ := mustGet(doc, "spec_kitty").(*jsonx.Object)
	if sk == nil {
		sk = &jsonx.Object{}
		doc = prepend(doc, "spec_kitty", sk)
	}
	changed := false
	if !sk.Has("schema_version") {
		sk = prepend(sk, "schema_version", CurrentSchemaVersion)
		changed = true
	}
	if !sk.Has("schema_capabilities") {
		sk.Set("schema_capabilities", capabilitiesObject())
		changed = true
	}
	if !changed {
		return false, nil
	}
	doc.Set("spec_kitty", sk)
	return true, writeInPlace(path, []byte(header+yamlx.Emit(doc)), 0o644)
}

// splitLeadingComments separates the leading comment/blank block (which
// ruamel preserves on round trip) from the document body.
func splitLeadingComments(s string) (string, string) {
	i := 0
	for i < len(s) {
		j := strings.IndexByte(s[i:], '\n')
		line := s[i:]
		if j >= 0 {
			line = s[i : i+j+1]
		}
		t := strings.TrimSpace(line)
		if t != "" && !strings.HasPrefix(t, "#") {
			break
		}
		i += len(line)
		if j < 0 {
			break
		}
	}
	return s[:i], s[i:]
}

func prepend(o *jsonx.Object, key string, v any) *jsonx.Object {
	out := jsonx.NewObject(key, v)
	for _, kv := range o.Pairs() {
		if kv.Key != key {
			out.Set(kv.Key, kv.Value)
		}
	}
	return out
}

// PlatformInfo returns (sys.platform, platform.platform()) equivalents.
func PlatformInfo() (string, string) {
	plat := runtime.GOOS
	if plat == "windows" {
		plat = "win32"
	}
	sys, rel, mach, ok := unameInfo()
	if !ok {
		return plat, runtime.GOOS
	}
	pv := sys + "-" + rel + "-" + mach
	if runtime.GOOS == "linux" {
		if out, err := exec.Command("getconf", "GNU_LIBC_VERSION").Output(); err == nil {
			f := strings.Fields(string(out))
			if len(f) == 2 && f[0] == "glibc" {
				pv += "-with-glibc" + f[1]
			}
		}
	}
	return plat, pv
}

// RuntimeVersion stands in for platform.python_version() in metadata.yaml
// (no consumer reads it; we record the Go toolchain version).
func RuntimeVersion() string { return strings.Fields(strings.TrimPrefix(runtime.Version(), "go"))[0] }

// NewMetadata builds init's metadata record for now.
func NewMetadata(version string) *Metadata {
	plat, pv := PlatformInfo()
	return &Metadata{Version: version, InitializedAt: clock.ISO(clock.Now().UTC()), PythonVersion: RuntimeVersion(), Platform: plat, PlatformVersion: pv}
}
