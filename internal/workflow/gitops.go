package workflow

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spec-kitty/go-kitty3/internal/clock"
	"github.com/spec-kitty/go-kitty3/internal/gitx"
)

// selfExe is the running spec-kitty binary (resolved once).
func selfExe() string {
	p, err := os.Executable()
	if err != nil {
		return "spec-kitty"
	}
	return p
}

// MergeEnv is _make_merge_env: PATH starts with the running binary's dir so
// the registered merge drivers (`spec-kitty merge-driver-*`) resolve to it.
func MergeEnv() []string {
	return []string{"PATH=" + filepath.Dir(selfExe()) + string(os.PathListSeparator) + os.Getenv("PATH")}
}

// git runs git in dir with the merge env and returns the raw result.
func git(dir string, args ...string) gitx.Result {
	r, err := gitx.Exec(dir, MergeEnv(), nil, args...)
	if err != nil {
		return gitx.Result{Code: 127, Stderr: err.Error()}
	}
	return r
}

// gitOut runs git and returns trimmed stdout ("" on failure).
func gitOut(dir string, args ...string) string {
	r := git(dir, args...)
	if r.Code != 0 {
		return ""
	}
	return strings.TrimSpace(r.Stdout)
}

// ExcludeFromGitIndex is core.git_ops.exclude_from_git_index: append
// patterns to the common-dir info/exclude (when that file exists).
func ExcludeFromGitIndex(repo string, patterns []string) {
	common, err := gitx.CommonDir(repo)
	if err != nil {
		return
	}
	p := filepath.Join(common, "info", "exclude")
	b, err := os.ReadFile(p)
	if err != nil {
		return
	}
	existing := map[string]bool{}
	for _, l := range strings.Split(string(b), "\n") {
		existing[l] = true
	}
	var add []string
	for _, pat := range patterns {
		if !existing[pat] {
			add = append(add, pat)
		}
	}
	if len(add) == 0 {
		return
	}
	f, err := os.OpenFile(p, os.O_APPEND|os.O_WRONLY, 0)
	if err != nil {
		return
	}
	defer f.Close()
	const marker = "# Added by spec-kitty (local exclusions)"
	if !existing[marker] {
		fmt.Fprintf(f, "\n%s\n", marker)
	}
	for _, pat := range add {
		fmt.Fprintf(f, "%s\n", pat)
	}
}

// laneTipHookSignature marks the lane-tip recorder hooks.
const laneTipHookSignature = "# Generated by spec-kitty (lane-tip recorder)."

// LaneTipHookBody is the post-commit/post-rewrite lane-tip recorder.
const LaneTipHookBody = "#!/bin/sh\n" + laneTipHookSignature + " Do not edit by hand.\n" +
	"b=$(git symbolic-ref -q HEAD) || exit 0\n" +
	"case \"$b\" in refs/heads/kitty/mission-*-lane-*) ;; *) exit 0 ;; esac\n" +
	"id=${b##*-lane-}\n" +
	"case \"$id\" in ''|*[!a-z]*) exit 0 ;; esac\n" +
	"git update-ref \"refs/spec-kitty/lane-tip/${b#refs/heads/}\" HEAD >/dev/null 2>&1\n" +
	"exit 0\n"

func hooksDir(repo string) string {
	d := gitOut(repo, "rev-parse", "--git-path", "hooks")
	if d == "" {
		return ""
	}
	if !filepath.IsAbs(d) {
		d = filepath.Join(repo, d)
	}
	return d
}

// InstallLaneTipRecorder is policy.lane_tip_recorder.install_lane_tip_recorder
// (empty or own slots only; foreign hooks are left untouched).
func InstallLaneTipRecorder(o *Out, repo string) {
	d := hooksDir(repo)
	if d == "" {
		return
	}
	os.MkdirAll(d, 0o755)
	for _, n := range []string{"post-commit", "post-rewrite"} {
		p := filepath.Join(d, n)
		if b, err := os.ReadFile(p); err == nil {
			if !strings.Contains(string(b), laneTipHookSignature) {
				o.Console(fmt.Sprintf("[yellow]⚠ %s is not spec-kitty-managed; skipping lane-tip recorder install for this hook (its content is left untouched). Lane work-tip recording will only happen at spec-kitty's own lane touches until this hook is spec-kitty-managed.[/yellow]", p))
				continue
			}
		}
		tmp := p + ".tmp"
		if os.WriteFile(tmp, []byte(LaneTipHookBody), 0o755) != nil {
			continue
		}
		os.Chmod(tmp, 0o755)
		os.Rename(tmp, p)
	}
}

// commitGuardSignature marks spec-kitty generated pre-commit hooks.
const commitGuardSignature = "# Generated by spec-kitty."

// InstallCommitGuard is policy.hook_installer.install: the pre-commit hook
// pinned to the running binary (`<bin> commit-guard-hook`), with the
// install-agnostic `spec-kitty` PATH fallback. A foreign hook is backed up
// first; returns the backup path ("" when none).
func InstallCommitGuard(repo string) string {
	hooks := filepath.Join(repo, ".git", "hooks")
	if err := os.MkdirAll(hooks, 0o755); err != nil {
		return ""
	}
	exe := selfExe()
	body := "#!/bin/sh\n" +
		"# Generated by spec-kitty. Do not edit by hand.\n" +
		"# Installed: " + clock.Now().UTC().Format("2006-01-02T15:04:05+00:00") + "\n" +
		"# Interpreter: " + exe + "\n" +
		"set -e\n" +
		"if [ -x \"" + exe + "\" ]; then\n" +
		"    exec \"" + exe + "\" commit-guard-hook \"$@\"\n" +
		"fi\n" +
		"if command -v spec-kitty >/dev/null 2>&1; then\n" +
		"    exec spec-kitty commit-guard-hook \"$@\"\n" +
		"fi\n" +
		"echo \"[spec-kitty guard] Pinned interpreter is gone: " + exe + "\" >&2\n" +
		"echo \"[spec-kitty guard] 'spec-kitty' is also not on PATH.\" >&2\n" +
		"echo \"[spec-kitty guard] Remedy: run 'spec-kitty migrate repin-hooks' from an environment where spec-kitty is installed and on PATH.\" >&2\n" +
		"exit 1\n"
	p := filepath.Join(hooks, "pre-commit")
	backup := ""
	if b, err := os.ReadFile(p); err == nil && !strings.Contains(string(b), commitGuardSignature) {
		backup = p + ".spec-kitty-backup-" + clock.Now().UTC().Format("20060102T150405Z")
		os.WriteFile(backup, b, 0o755)
	}
	tmp := p + ".tmp"
	if os.WriteFile(tmp, []byte(body), 0o700) != nil {
		return backup
	}
	os.Chmod(tmp, 0o700)
	os.Rename(tmp, p)
	return backup
}
