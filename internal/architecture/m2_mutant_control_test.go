func validateM2MutantCensus(values []string) error {
	seen := make(map[string]bool, len(values))
	for _, value := range values {
		if value == "" || seen[value] {
			return fmt.Errorf("duplicate or empty mutant %q", value)
		}
		seen[value] = true
	}
	want := m2MutantRegistry()
	slices.Sort(want)
	got := slices.Clone(values)
	slices.Sort(got)
	if !slices.Equal(got, want) {
		return fmt.Errorf("mutant census observed=%v expected=%v", got, want)
	}
	return nil
}

func TestM2MalformedSourceFailsClosedAndBounded(t *testing.T) {
	root := t.TempDir()
	writeGoFixture(t, root, "go.mod", "module example.test/malformed\n\ngo 1.26\n")
	writeGoFixture(t, root, "internal/mission/broken.go", "package mission\nimport (")
	started := time.Now()
	_, err := scanM2AllGoImports(root, "example.test/malformed")
	if err == nil {
		t.Fatal("evidence=TYPE-AST-REACHABILITY malformed source observed=accepted expected=rejected")
	}
	if elapsed := time.Since(started); elapsed > time.Second {
		t.Fatalf("evidence=TYPE-AST-REACHABILITY malformed source elapsed=%s expected<=1s", elapsed)
	}
	if len(err.Error()) > 2048 {
		t.Fatalf("evidence=TYPE-AST-REACHABILITY diagnostic-bytes=%d expected<=2048", len(err.Error()))
	}
}
